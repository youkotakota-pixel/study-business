function buildDays(): CurriculumDay[] {
  const days: CurriculumDay[] = [];
  let day = 1;

  for (const block of MONTHLY_BLOCKS) {
    for (const title of block.topics) {
      days.push({
        day,
        category: block.category,
        title,
        objective: `${block.category}の「${title}」を、図面が読めない前提で仕組みとして理解する`,
      });
      day += 1;
    }
  }

  if (days.length !== 365) {
    throw new Error(`カリキュラム日数が365ではありません: ${days.length}`);
  }

  return days;
}

const curriculum = {
  total_days: 365,
  days: buildDays(),
};

const outPath = join(ROOT, "curriculum", "index.yaml");
writeFileSync(outPath, stringifyYaml(curriculum), "utf8");
console.log(`Wrote ${outPath} (${curriculum.total_days} days)`);
